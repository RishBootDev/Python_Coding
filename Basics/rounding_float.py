# Rounding to the nearest integer
num1 = 4.6
print(round(num1))  
# Output: 5

# Rounding to two decimal places
num2 = 4.5678
print(round(num2, 2))  
# Output: 4.57

# Rounding 4.5 - demonstrates "banker's rounding"
num4 = 4.5
print(round(num4))  
# Output: 4